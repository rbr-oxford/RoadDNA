// Helper functions
export const getRandomCondition = () => {
  const conditions = ['Good', 'Moderate', 'High Risk'];
  return conditions[Math.floor(Math.random() * conditions.length)];
};

export const getConditionColor = (condition) => {
  const colors = {
    'Good': 'text-green-400 border-green-500/30 bg-green-500/10',
    'Moderate': 'text-yellow-400 border-yellow-500/30 bg-yellow-500/10',
    'High Risk': 'text-red-400 border-red-500/30 bg-red-500/10'
  };
  return colors[condition] || 'text-blue-400 border-blue-500/30 bg-blue-500/10';
};

